"""Contracts implemented by camera and image-decoder adapters."""
from typing import Any,Callable,Protocol

class ImageFrame(Protocol):
    shape:tuple[int,...]

class CameraPort(Protocol):
    def get(self,endpoint:str,**params:Any)->dict:...
    def state(self)->dict:...
    def info(self)->dict:...
    def preview(self,enabled:bool,port:int=8554)->dict:...
    def shutter(self,enabled:bool)->dict:...
    def media(self)->dict:...
    def fetch_media_bytes(self,folder:str,name:str,cancelled:Callable[[],bool])->bytes:...
    def delete_media(self,folder:str,name:str)->dict:...

class FrameDecoder(Protocol):
    def photo(self,source:bytes)->ImageFrame:...
    def video(self,source:bytes,cancelled:Callable[[],bool])->ImageFrame:...
